#!/usr/bin/env python3
"""Render the "Mission Logs" cards in index.html from blog/posts.json.

Keeps the cards as real, crawlable HTML (the page also refreshes them from
blog/posts.json in the browser). Run it after adding or editing posts:  python3 build-logs.py
"""
import html, json, pathlib, re

here = pathlib.Path(__file__).resolve().parent
posts = json.loads((here / 'blog' / 'posts.json').read_text(encoding='utf-8'))
posts = sorted((p for p in posts if not p.get('draft')), key=lambda p: p['date'], reverse=True)
e = html.escape

cards = []
# LOG.001 is the oldest entry
numbered = {p['slug']: n for n, p in enumerate(reversed(posts), 1)}
for p in posts:
    n = numbered[p['slug']]
    tags = ''.join(f'<span>{e(t)}</span>' for t in p.get('tags', []))
    cards.append(f'''          <li class="card" data-reveal><article class="panel log" data-tilt>
            <p class="panel-label">LOG.{n:03d} &nbsp;//&nbsp; <time datetime="{e(p['date'])}">{e(p['date'])}</time> &nbsp;//&nbsp; {e(p.get('readTime', ''))}</p>
            <h3 data-scramble>{e(p['title'])}</h3>
            <p data-type>{e(p['excerpt'])}</p>
            <p class="tags">{tags}</p>
            <a class="read glitch" href="log.html?slug={e(p['slug'])}" aria-label="Read log {n:03d}: {e(p['title'])}">READ →</a>
          </article></li>''')

block = ('<!-- LOGS:START (generated by build-logs.py from blog/posts.json) -->\n'
         '        <ul class="grid grid-3">\n' + '\n'.join(cards) + '\n        </ul>\n        <!-- LOGS:END -->')
index = here / 'index.html'
src = index.read_text(encoding='utf-8')
new = re.sub(r'<!-- LOGS:START.*?<!-- LOGS:END -->', lambda m: block, src, flags=re.S)
index.write_text(new, encoding='utf-8')
print(f'Wrote {len(posts)} mission logs into index.html')
